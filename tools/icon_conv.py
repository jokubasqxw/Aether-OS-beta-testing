#!/usr/bin/env python3
"""
icon_conv.py - Convert icon images (PNG/BMP) to C header files for AetherOS.

Usage:
    python3 tools/icon_conv.py input.png output.h [icon_name]

Example:
    python3 tools/icon_conv.py my_icon.png icons.h "MY_ICON"
"""

import sys
import struct
from PIL import Image

def convert_to_c_array(image_path, output_path, icon_name="icon"):
    """Convert an image to a C array and write it to a header file."""
    img = Image.open(image_path).convert("RGBA")
    width, height = img.size

    # Check if image is a reasonable size for icons
    max_size = 64
    if width > max_size or height > max_size:
        print(f"Warning: image {width}x{height} is larger than {max_size}x{max_size}, resizing...")
        img = img.resize((max_size, max_size), Image.LANCZOS)

    # Convert to 32-bit RGBA format
    pixels = list(img.getdata())
    pixel_bytes = b''
    for p in pixels:
        pixel_bytes += struct.pack('BBBB', p[0], p[1], p[2], p[3])

    # Generate C array
    c_array = f"// Auto-generated by icon_conv.py\n// From: {image_path}\n// Size: {width}x{height}\n\n"
    c_array += f"#ifndef {icon_name.upper()}_H\n"
    c_array += f"#define {icon_name.upper()}_H\n\n"
    c_array += f"#include <stdint.h>\n\n"
    c_array += f"// {icon_name} icon data ({width}x{height}, RGBA)\n"
    c_array += f"// {len(pixels)} pixels\n"
    c_array += f"const uint8_t {icon_name}_data[] = {{\n"

    # Write in rows (each row on a separate line for readability)
    row_size = width * 4  # 4 bytes per pixel (RGBA)
    for y in range(height):
        c_array += "    "
        for x in range(width):
            idx = (y * width + x) * 4
            r, g, b, a = pixel_bytes[idx], pixel_bytes[idx+1], pixel_bytes[idx+2], pixel_bytes[idx+3]
            c_array += f"0x{r:02X}, 0x{g:02X}, 0x{b:02X}, 0x{a:02X}"
            if x < width - 1:
                c_array += ", "
        if y < height - 1:
            c_array += ","
        c_array += "\n"

    c_array += "};\n\n"
    c_array += f"#endif // {icon_name.upper()}_H\n"

    with open(output_path, 'w') as f:
        f.write(c_array)

    print(f"Generated: {output_path}")
    print(f"  Size: {width}x{height}")
    print(f"  Pixels: {len(pixels)}")
    print(f"  File size: {len(pixel_bytes)} bytes")

def main():
    if len(sys.argv) < 3:
        print(__doc__)
        sys.exit(1)

    input_path = sys.argv[1]
    output_path = sys.argv[2]
    icon_name = sys.argv[3] if len(sys.argv) > 3 else "icon"

    convert_to_c_array(input_path, output_path, icon_name)

if __name__ == "__main__":
    main()
